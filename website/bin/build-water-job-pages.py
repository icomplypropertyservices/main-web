    if len(JOBS) != 120:
        raise SystemExit(f"expected 120 jobs, got {len(JOBS)}")
    slugs = [row[0] for row in JOBS]
    if len(set(slugs)) != 120:
        raise SystemExit("duplicate slugs in JOBS")
    angles = [row[5] for row in JOBS]
    if len(set(angles)) != 120:
        raise SystemExit("duplicate angles in JOBS")
    counts: dict[str, int] = {}
    for row in JOBS:
        counts[row[2]] = counts.get(row[2], 0) + 1
    if counts != expected:
        raise SystemExit(f"sublane counts {counts} != {expected}")

    existing: set[str] = set()
    if KEYWORDS.is_file():
        raw = json.loads(KEYWORDS.read_text())
        if isinstance(raw, dict):
            existing = {re.sub(r"[^a-z0-9]+", "-", k.lower()).strip("-") for k in raw}
    clashes = sorted(set(slugs) & existing)
    if clashes:
        raise SystemExit("slug clash with keywords.json: " + ", ".join(clashes[:12]))

    by_lane: dict[str, list[str]] = {k: [] for k in expected}
    for slug, _name, lane, *_rest in JOBS:
        by_lane[lane].append(slug)

    banned = [
        r"£\s*\d",
        r"UKAS",
        r"WaterSafe",
        r"WRAS approved",
        r"approved installer",
        r"G3 registered",
        r"G3 qualified",
        r"scheme membership number",
    ]
