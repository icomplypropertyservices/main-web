def union_slugs() -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for key in ("core_money", "compliance_packs", "live_keywords"):
        for slug in INDEX[key]:
            if slug not in seen:
                seen.add(slug)
                out.append(slug)
    for slug in INDEX["canonical_jobs"].values():
        if slug not in seen:
            seen.add(slug)
            out.append(slug)
    return out


def bucket_for(slug: str) -> str:
    if slug in INDEX["core_money"]:
        return "core_money"
    if slug in INDEX["compliance_packs"]:
        return "compliance_packs"
    if slug in INDEX["live_keywords"]:
        return "live_keywords"
    return "live_service_job"


def build_row(slug: str, facts: dict) -> dict:
    master = MASTER[slug]
    name = master.get("name") or facts["primary"].title()
    service = master.get("service") or "electrical"
    # Prefer a more accurate service when the master filed fire-door inspection under fire-alarms.
    if slug in ("fire-door-inspection", "fire-door-compliance"):
        service = "fire-doors"
    if slug == "pat-testing":
        service = "pat-testing" if slug in MASTER else service
        # master has pat-testing under electrical; keep electrical if that is the live catalogue home
        service = master.get("service") or "electrical"
    if slug == "smoke-alarm-installation":
        service = master.get("service") or "smoke-co-alarms"
    related = master.get("related") or slug
    primary = facts["primary"]
    intro = (
        f"{facts['h1'].split('—')[0].strip()} is {facts['angle']}. "
        f"iComply delivers this for {facts['who']} from Stockport SK2 across Greater Manchester and the North West. "
        f"{facts['not']} Quotes are written POA after we know the property — we do not invent a catalogue £ price."
    )
    body = (
        f"The visit is scoped against {facts['standards']}. Typical scope includes {facts['includes']}. "
        f"{facts['not']} "
        f"North West stock for this job runs from terraces and purpose-built flats to HMOs, offices and light industrial. "
        f"We say when {primary} is the right next step and when a wider service visit is safer. "
        f"Enquire with postcode, property type and any brand already on site. WhatsApp and phone are on this page."
    )
    meta = (
        f"{name} for {facts['who']} across Greater Manchester and the North West. "
        f"{facts['standards']}. Written POA quote from Stockport — no invented £ prices."
    )
    if len(meta) > 165:
        meta = f"{name} across the North West. {facts['standards']}. POA after scope from Stockport engineers."
    title = facts["title"]
    if len(title) > 65:
        title = f"{name} | iComply North West"
    focus = [
        f"Scoped against {facts['standards']}",
        "Written POA quote — no invented £ on this page",
        facts["includes"].split(",")[0].strip().capitalize()
        if facts["includes"]
        else f"Site look for {primary}",
        "Stockport engineers covering 150+ North West towns",
    ]
    faqs = [[q, a] for q, a in facts["faqs"]]
    row = {
        "slug": slug,
        "name": name,
        "service": service,
        "related": related,
        "bucket": bucket_for(slug),
        "seo_title": title,
        "h1": facts["h1"],
        "primary": primary,
        "secondaries": facts.get("seconds") or [primary + " North West"],
        "intro": intro,
        "body": body,
        "meta_desc": meta,
        "seo_keywords": f"{primary}, {name}, {facts['standards']}, North West, Stockport, POA",
        "focus_points": focus,
        "faq": faqs,
    }
    if facts.get("mfr"):
        row["manufacturers"] = facts["mfr"]
    if facts.get("extra"):
        row["extra_manufacturer_names"] = facts["extra"]
    return row


def main() -> None:
    facts = {**FACTS, **MORE}
    slugs = union_slugs()
    missing = [s for s in slugs if s not in facts]
    if missing:
        raise SystemExit("Missing facts for: " + ", ".join(missing))
    jobs = [build_row(s, facts[s]) for s in slugs]
    titles = [j["seo_title"] for j in jobs]
    h1s = [j["h1"] for j in jobs]
    if len(titles) != len(set(titles)):
        raise SystemExit("Duplicate seo_title in pack")
    if len(h1s) != len(set(h1s)):
        raise SystemExit("Duplicate h1 in pack")
    payload = {
        "slice": "core-compliance-live",
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "count": len(jobs),
        "jobs": jobs,
    }
    out = ROOT / "data/job-packs/core-compliance-live.json"
    out.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {len(jobs)} overlays → {out}")
    print("core_money", sum(1 for j in jobs if j["bucket"] == "core_money"))
    print("compliance_packs", sum(1 for j in jobs if j["bucket"] == "compliance_packs"))
    print("live_keywords_only", sum(1 for j in jobs if j["bucket"] == "live_keywords"))
    print("live_service_job", sum(1 for j in jobs if j["bucket"] == "live_service_job"))


if __name__ == "__main__":
    main()
