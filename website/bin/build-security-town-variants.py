#!/usr/bin/env python3
"""Per-town wording index for netlify/lib/security-town-copy.js (SEO PR145, 2026-10-20).

A town's index i picks variant (i + slot offset + k) % K in each slot (K = 5, 7, 8, 9, 11, 13,
17, 19, pairwise coprime). Two towns share a slot's wording only when K divides the difference
of their indices, so any two of the 269 towns share at most two slots. This assigns indices
(a permutation of 0..268) so that towns near each other (same council, within 15 miles, or
listed as neighbours) share no slot at all where possible. Deterministic.
Writes website/data/security-town-variants.json.
"""
import json, math, os, random
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
doc = json.load(open(os.path.join(ROOT, "data/security-dual-ring-p0.json")))
geo = json.load(open(os.path.join(ROOT, "data/town-geo-slim.json")))
MODS = [5, 7, 8, 9, 11, 13, 17, 19]
towns = sorted(doc["towns"])
def ll(t):
    g = geo.get(t)
    return (g[5], g[6], g[0]) if g else (None, None, doc["towns"][t].get("county"))
P = {t: ll(t) for t in towns}
def miles(a, b):
    if a[0] is None or b[0] is None: return 999
    k = math.pi / 180
    h = math.sin((b[0]-a[0])*k/2)**2 + math.cos(a[0]*k)*math.cos(b[0]*k)*math.sin((b[1]-a[1])*k/2)**2
    return 7917.6*math.asin(min(1, math.sqrt(h)))
def near(a, b):
    return P[a][2] == P[b][2] or miles(P[a], P[b]) < 15 or b in doc["towns"][a].get("near", []) or a in doc["towns"][b].get("near", [])
def shared(d): return sum(1 for m in MODS if d % m == 0)
N = len(towns)
nb = {t: [u for u in towns if u != t and near(t, u)] for t in towns}
order = sorted(towns, key=lambda t: -len(nb[t]))  # most-constrained first
rng = random.Random(20261020)
idx, free = {}, list(range(N))
for t in order:
    best = None
    rng.shuffle(free)
    for c in free:
        w = [shared(abs(c - idx[u])) * (5 if not doc["towns"][t].get("county") else 1) for u in nb[t] if u in idx]
        sc = (max(w) if w else 0, sum(w))
        if best is None or sc < best[0]: best = (sc, c)
        if sc == (0, 0): break
    idx[t] = best[1]; free.remove(best[1])
worst = max((shared(abs(idx[a]-idx[b])) for a in towns for b in nb[a]), default=0)
bad = sum(1 for a in towns for b in nb[a] if shared(abs(idx[a]-idx[b])))//2
json.dump({"_doc": "Generated by website/bin/build-security-town-variants.py: town -> wording index for security-town-copy.js.", "towns": {t: idx[t] for t in towns}}, open(os.path.join(ROOT, "data/security-town-variants.json"), "w"), separators=(",", ":"))
print(f"towns={N} near pairs sharing a slot: {bad}; worst near-pair shared slots: {worst}")
